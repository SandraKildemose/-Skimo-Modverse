function localeFromCountry(country) {
  const c = String(country || "").toLowerCase();
  if (c === "denmark") return "da";
  if (c === "sweden") return "sv";
  if (c === "norway") return "no";
  if (c === "france") return "fr";
  if (c === "usa" || c === "uk") return "en";
  return "da";
}

