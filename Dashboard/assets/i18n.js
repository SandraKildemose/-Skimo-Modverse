	function safeStorageGet(key) {
		try { return localStorage.getItem(key); } catch { return null; }
	}

	function safeStorageSet(key, value) {
		try { localStorage.setItem(key, value); } catch {}
	}

	function normalizeLang(lang) {
		if (!lang) return null;
		const l = String(lang).toLowerCase();
		if (l.startsWith('da')) return 'da';
		if (l.startsWith('sv')) return 'sv';
		if (l.startsWith('no') || l.startsWith('nb') || l.startsWith('nn')) return 'no';
		if (l.startsWith('en')) return 'en';
		if (l.startsWith('fr')) return 'fr';
		if (SUPPORTED_LANGS.has(l)) return l;
		return null;
	}

	function getLanguageFromQuery() {
		try {
			const url = new URL(window.location.href);
			const q = normalizeLang(url.searchParams.get('lang'));
			if (q && SUPPORTED_LANGS.has(q)) return q;
		} catch {}
		return null;
	}

	function detectPreferredLanguage() {
		const candidates = [];
		try {
			if (Array.isArray(navigator.languages)) {
				candidates.push(...navigator.languages);
			}
		} catch {}
		try {
			candidates.push(navigator.language);
		} catch {}
		try {
			candidates.push(Intl.DateTimeFormat().resolvedOptions().locale);
		} catch {}

		for (const candidate of candidates) {
			const normalized = normalizeLang(candidate);
			// Skip generic English for auto-detect so the site defaults to Danish until the user picks a flag.
			if (normalized === 'en') continue;
			if (normalized && SUPPORTED_LANGS.has(normalized)) return normalized;
		}

		// Timezone fallback if browser language is unavailable/unsupported.
		try {
			const tz = String(Intl.DateTimeFormat().resolvedOptions().timeZone || '').toLowerCase();
			if (tz.includes('stockholm')) return 'sv';
			if (tz.includes('copenhagen')) return 'da';
			if (tz.includes('oslo')) return 'no';
			if (tz.includes('paris')) return 'fr';
		} catch {}

		return DEFAULT_LANG;
	}

	function getLanguage() {
		const stored = normalizeLang(safeStorageGet('lang'));
		const version = safeStorageGet('lang_version');
		const source = safeStorageGet(LANG_SOURCE_KEY);

		// Language chosen via flags / menu must win over ?lang= i URL (fx delte links),
		// otherwise every applyTranslations() resets the page to the URL language.
		if (source === 'manual' && stored && SUPPORTED_LANGS.has(stored)) {
			return stored;
		}

		const q = getLanguageFromQuery();
		if (q) {
			safeStorageSet('lang_version', LANG_STORAGE_VERSION);
			safeStorageSet('lang', q);
			safeStorageSet(LANG_SOURCE_KEY, 'manual');
			return q;
		}

		// Keep manual user choice across app updates.
		if (version !== LANG_STORAGE_VERSION) {
			if (stored && SUPPORTED_LANGS.has(stored) && source === 'manual') {
				safeStorageSet('lang_version', LANG_STORAGE_VERSION);
				return stored;
			}
			const detected = detectPreferredLanguage();
			safeStorageSet('lang_version', LANG_STORAGE_VERSION);
			safeStorageSet('lang', detected);
			safeStorageSet(LANG_SOURCE_KEY, 'auto');
			return detected;
		}

		if (stored && SUPPORTED_LANGS.has(stored)) return stored;
		const detected = detectPreferredLanguage();
		safeStorageSet('lang', detected);
		safeStorageSet(LANG_SOURCE_KEY, 'auto');
		return detected;
	}

	function escapeRegExp(s) {
		return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
	}

	function t(key, vars) {
		const lang = getLanguage();
		let str = (translations[lang] && translations[lang][key]) || translations[DEFAULT_LANG][key] || key;
		if (vars && str && typeof str === 'string') {
			for (const [k, v] of Object.entries(vars)) {
				str = str.replace(new RegExp(`\\{\\{\\s*${escapeRegExp(k)}\\s*\\}\\}`, 'g'), String(v));
			}
		}
		return str;
	}

	const ALLOWED_I18N_HTML_TAGS = new Set(['A', 'B', 'BR', 'EM', 'I', 'LI', 'P', 'SMALL', 'SPAN', 'STRONG', 'UL']);

	function sanitizeI18nHtml(raw) {
		if (typeof raw !== 'string' || !raw) return '';
		const template = document.createElement('template');
		template.innerHTML = raw;

		const cleanNode = (node) => {
			if (!node || node.nodeType !== Node.ELEMENT_NODE) return;
			const tag = node.tagName;
			if (!ALLOWED_I18N_HTML_TAGS.has(tag)) {
				const text = document.createTextNode(node.textContent || '');
				node.replaceWith(text);
				return;
			}

			const attrs = Array.from(node.attributes || []);
			for (const attr of attrs) {
				const name = String(attr.name || '').toLowerCase();
				const value = String(attr.value || '');
				const isHref = tag === 'A' && name === 'href';
				const isSafeAttr = name === 'class' || name === 'title' || name === 'aria-label';
				if (isHref) {
					const trimmed = value.trim();
					const safeHref =
						/^(https?:|mailto:|tel:|\/|#)/i.test(trimmed) &&
						!/^\s*javascript:/i.test(trimmed) &&
						!/^\s*data:/i.test(trimmed);
					if (!safeHref) node.removeAttribute(attr.name);
					continue;
				}
				if (tag === 'A' && (name === 'target' || name === 'rel')) continue;
				if (name.startsWith('on') || !isSafeAttr) node.removeAttribute(attr.name);
			}

			if (tag === 'A') {
				const t = String(node.getAttribute('target') || '')
					.replace(/\s+/g, '')
					.toLowerCase();
				if (t === '_blank') {
					const relRaw = (node.getAttribute('rel') || '').trim();
					const tokens = new Set(
						relRaw
							.split(/\s+/)
							.map((s) => s.toLowerCase())
							.filter(Boolean)
					);
					tokens.add('noopener');
					tokens.add('noreferrer');
					node.setAttribute('rel', Array.from(tokens).join(' '));
				}
			}

			Array.from(node.childNodes || []).forEach(cleanNode);
		};

		Array.from(template.content.childNodes || []).forEach(cleanNode);
		return template.innerHTML;
	}

	function setLanguage(lang, opts = {}) {
		const next = normalizeLang(lang) || DEFAULT_LANG;
		safeStorageSet('lang', next);
		safeStorageSet('lang_version', LANG_STORAGE_VERSION);
		safeStorageSet(LANG_SOURCE_KEY, opts && opts.source === 'auto' ? 'auto' : 'manual');
		applyTranslations(document);
		wireReturnCarry(document);
		try {
			document.dispatchEvent(new CustomEvent('skimo:languagechange', { detail: { lang: getLanguage() } }));
		} catch {}
	}

	function applyTranslations(root) {
		const lang = getLanguage();
		try {
			document.documentElement.setAttribute('lang', lang === 'no' ? 'nb' : lang);
		} catch {}

		// Translate simple text nodes
		root.querySelectorAll('[data-i18n]').forEach(el => {
			const key = el.getAttribute('data-i18n');
			const text = t(key);
			if (text) {
				el.textContent = text;
			}
		});

		// Translate HTML nodes (allows <br>, <strong>, etc.)
		root.querySelectorAll('[data-i18n-html]').forEach(el => {
			const key = el.getAttribute('data-i18n-html');
			const html = t(key);
			if (html) {
				el.innerHTML = sanitizeI18nHtml(html);
			}
		});

		// Translate common attributes (placeholder/title/value/aria-label/alt)
		root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
			const key = el.getAttribute('data-i18n-placeholder');
			const text = t(key);
			if (text) el.setAttribute('placeholder', text);
		});
		root.querySelectorAll('[data-i18n-title]').forEach(el => {
			const key = el.getAttribute('data-i18n-title');
			const text = t(key);
			if (text) el.setAttribute('title', text);
		});
		root.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
			const key = el.getAttribute('data-i18n-aria-label');
			const text = t(key);
			if (text) el.setAttribute('aria-label', text);
		});
		root.querySelectorAll('[data-i18n-alt]').forEach(el => {
			const key = el.getAttribute('data-i18n-alt');
			const text = t(key);
			if (text) el.setAttribute('alt', text);
		});
		root.querySelectorAll('[data-i18n-value]').forEach(el => {
			const key = el.getAttribute('data-i18n-value');
			const text = t(key);
			if (text) {
				try { el.value = text; } catch {}
				el.setAttribute('value', text);
			}
		});

		// Translate trade fee with percent
		root.querySelectorAll('[data-fee-percent]').forEach(el => {
			const percent = el.getAttribute('data-fee-percent');
			el.textContent = `${percent}% ${t('tradeFee')}`;
		});

		// Format currencies
		formatAllCurrencies(root, lang);

		// Set selectors value to current lang
		root.querySelectorAll('select.language-selector, .language-selector select').forEach(sel => {
			// Handle both select.language-selector and container .language-selector > select
			const selectEl = sel.tagName.toLowerCase() === 'select' ? sel : sel.querySelector('select');
			if (!selectEl) return;
			selectEl.value = lang;
		});
	}

	function formatAllCurrencies(root, lang) {
		const conf = currencyConfig[lang] || currencyConfig[DEFAULT_LANG];
		const nf = new Intl.NumberFormat(conf.locale, { style: 'currency', currency: conf.currency, maximumFractionDigits: 0 });

		root.querySelectorAll('[data-amount]').forEach(el => {
			const baseAmount = parseFloat(el.getAttribute('data-amount')) || 0;
			const baseCurrency = (el.getAttribute('data-base-currency') || 'DKK').toUpperCase();

			let amountInTarget = baseAmount;
			if (baseCurrency === 'DKK') {
				amountInTarget = baseAmount * (conf.currency === 'SEK' ? ratesFromDKK.SEK : ratesFromDKK.DKK);
			}
			const priceText = baseAmount === 0 ? t('price.free') : `${nf.format(Math.round(amountInTarget))} / ${t('perMonth')}`;
			el.textContent = priceText;
		});
	}

	function safeUrl(urlLike) {
		try {
			return new URL(urlLike, window.location.href);
		} catch {
			return null;
		}
	}

	function isSameLocalSite(targetUrl) {
		const currentUrl = safeUrl(window.location.href);
		if (!targetUrl || !currentUrl) return false;
		if (targetUrl.protocol === 'file:' && currentUrl.protocol === 'file:') return true;
		return targetUrl.origin === currentUrl.origin;
	}

	function normalizeLocalTarget(urlLike) {
		const parsed = safeUrl(urlLike);
		if (!parsed) return null;
		if (!isSameLocalSite(parsed)) return null;
		const target = `${parsed.pathname}${parsed.search}${parsed.hash}`;
		const current = `${window.location.pathname}${window.location.search}${window.location.hash}`;
		return target === current ? null : target;
	}

	function getCurrentLocalTarget() {
		return `${window.location.pathname}${window.location.search}${window.location.hash}`;
	}

	const BACK_STACK_KEY = 'skimo_back_stack_v1';
	const LAST_PAGE_KEY = 'skimo_last_page_v1';
	const CURRENT_PAGE_KEY = 'skimo_current_page_v1';

	function readBackStack() {
		try {
			const raw = sessionStorage.getItem(BACK_STACK_KEY);
			const parsed = JSON.parse(raw || '[]');
			return Array.isArray(parsed) ? parsed.filter(item => typeof item === 'string' && item.trim()) : [];
		} catch {
			return [];
		}
	}

	function writeBackStack(stack) {
		try {
			sessionStorage.setItem(BACK_STACK_KEY, JSON.stringify(stack.slice(-40)));
		} catch {}
	}

	function rememberCurrentPage() {
		const current = getCurrentLocalTarget();
		try {
			const prevCurrent = normalizeLocalTarget(sessionStorage.getItem(CURRENT_PAGE_KEY));
			let candidatePrevious = prevCurrent && prevCurrent !== current ? prevCurrent : null;
			if (!candidatePrevious) {
				const fromReferrer = normalizeLocalTarget(document.referrer);
				if (fromReferrer && fromReferrer !== current) candidatePrevious = fromReferrer;
			}
			if (candidatePrevious) sessionStorage.setItem(LAST_PAGE_KEY, candidatePrevious);
			sessionStorage.setItem(CURRENT_PAGE_KEY, current);
		} catch {}
		const stack = readBackStack();
		if (stack[stack.length - 1] !== current) {
			stack.push(current);
			writeBackStack(stack);
		}
	}

	function getImmediatePreviousPage() {
		try {
			return normalizeLocalTarget(sessionStorage.getItem(LAST_PAGE_KEY));
		} catch {
			return null;
		}
	}

	function getPreviousTrackedPage() {
		const current = getCurrentLocalTarget();
		const stack = readBackStack();
		while (stack.length && stack[stack.length - 1] === current) {
			stack.pop();
		}
		writeBackStack(stack);
		return stack.length ? stack[stack.length - 1] : null;
	}

	function tryNavigateIfAllowed(target, isAllowedTarget) {
		if (!target || !isAllowedTarget(target)) return false;
		try {
			window.location.href = target;
			return true;
		} catch {
			return false;
		}
	}

	function smartBack(fallbackHref) {
		const current = getCurrentLocalTarget();
		function isAllowedTarget(target) {
			if (!target) return false;
			try {
				const u = safeUrl(target);
				if (!u) return false;
				if (!isSameLocalSite(u)) return false;
				const p = String(u.pathname || '/').toLowerCase();
				if (!p || p === 'null' || p === 'undefined') return false;
				return true;
			} catch {
				return false;
			}
		}

		// 1-step back behavior: always prefer the immediate previous internal page.
		const immediatePreviousRaw = getImmediatePreviousPage();
		const immediatePrevious = immediatePreviousRaw && immediatePreviousRaw !== current ? immediatePreviousRaw : null;
		if (tryNavigateIfAllowed(immediatePrevious, isAllowedTarget)) return true;

		const fromReferrer = normalizeLocalTarget(document.referrer);
		if (tryNavigateIfAllowed(fromReferrer, isAllowedTarget)) return true;

		const normalizedFallback = normalizeLocalTarget(fallbackHref);
		if (tryNavigateIfAllowed(normalizedFallback, isAllowedTarget)) return true;

		// Hard fallback: try browser history once, then home.
		try {
			if (window.history && window.history.length > 1) {
				window.history.back();
				return true;
			}
		} catch {}
		try {
			window.location.href = '/index.html';
			return true;
		} catch {}
		try {
			window.location.href = 'index.html';
			return true;
		} catch {}
		return false;
	}

	function withReturnParam(href) {
		const target = safeUrl(href);
		if (!target) return href;
		if (!isSameLocalSite(target)) return href;

		// Rene URL'er på eget domæne: tilføj ikke ?return=… eller ?lang=… på hvert link.
		// — Sprog ligger i localStorage via setLanguage / getLanguage.
		// — "Tilbage" bruger ?return= hvis den findes (gamle bogmærker), ellers session back-stack
		//   (rememberCurrentPage) og til sidst document.referrer.
		return `${target.pathname}${target.search}${target.hash}`;
	}

	function rememberImmediatePreviousBeforeNavigate(href) {
		const target = normalizeLocalTarget(href);
		const current = getCurrentLocalTarget();
		if (!target || !current || target === current) return;
		try {
			sessionStorage.setItem(LAST_PAGE_KEY, current);
		} catch {}
	}

	function navigateWithReturn(href) {
		const targetHref = withReturnParam(href);
		rememberImmediatePreviousBeforeNavigate(targetHref);
		window.location.href = targetHref;
	}

	function wireSmartBackLinks(root) {
		root.querySelectorAll('a[data-i18n="nav.return"], a[data-smart-back="true"], a.back-link').forEach(link => {
			if (link.dataset.smartBackBound === '1') return;
			link.dataset.smartBackBound = '1';
			link.addEventListener('click', (event) => {
				event.preventDefault();
				const mode = String(link.getAttribute('data-back-mode') || '').toLowerCase();
				if (mode === 'index') {
					smartBack('index.html');
					return;
				}
				if (mode === 'dashboard') {
					smartBack('index.html');
					return;
				}
				const fallbackHref = normalizeLocalTarget(link.getAttribute('href')) || 'index.html';
				smartBack(fallbackHref);
			});
		});
	}

	function wireReturnCarry(root) {
		root.querySelectorAll('a[href]').forEach(link => {
			const href = link.getAttribute('href') || '';
			if (!href || href.startsWith('#') || href.startsWith('mailto:') || href.startsWith('tel:') || href.startsWith('javascript:')) return;
			if (link.matches('a[data-i18n="nav.return"], a[data-smart-back="true"], a.back-link')) return;
			link.setAttribute('href', withReturnParam(href));
			if (link.dataset.returnCarryBound === '1') return;
			link.dataset.returnCarryBound = '1';
			link.addEventListener('click', () => {
				rememberImmediatePreviousBeforeNavigate(link.href || href);
			});
		});
	}

	function wireLanguageSelectors() {
		document.querySelectorAll('select.language-selector, .language-selector select').forEach(sel => {
			const selectEl = sel.tagName && sel.tagName.toLowerCase() === 'select' ? sel : sel.querySelector('select');
			if (!selectEl) return;
			selectEl.addEventListener('change', (e) => {
				const value = e.target.value;
				setLanguage(value, { source: 'manual' });
			});
		});
	}

	function polishVisibleTextValue(value, trimResult) {
		const text = String(value || '')
			.replace(/[—–]+/g, ' ')
			.replace(/\s+-\s+/g, ' ')
			.replace(/([A-Za-zÆØÅæøåÀ-ÖØ-öø-ÿ])\-([A-Za-zÆØÅæøåÀ-ÖØ-öø-ÿ])/g, '$1$2')
			.replace(/\s{2,}/g, ' ');
		return trimResult ? text.trim() : text;
	}

	function polishVisibleText(root) {
		const scope = root && root.nodeType ? root : document;
		const blockedTags = new Set(['SCRIPT', 'STYLE', 'CODE', 'PRE', 'TEXTAREA']);
		const polishNode = (node) => {
			if (!node || !node.parentElement || blockedTags.has(node.parentElement.tagName)) return;
			const original = node.nodeValue || '';
			if (!/[—–]|\s-\s|[A-Za-zÆØÅæøåÀ-ÖØ-öø-ÿ]\-[A-Za-zÆØÅæøåÀ-ÖØ-öø-ÿ]/.test(original)) return;
			const polished = polishVisibleTextValue(original, false);
			if (polished && polished !== original) node.nodeValue = polished;
		};
		try {
			const walker = document.createTreeWalker(scope, NodeFilter.SHOW_TEXT, {
				acceptNode(node) {
					if (!node.parentElement || blockedTags.has(node.parentElement.tagName)) return NodeFilter.FILTER_REJECT;
					return NodeFilter.FILTER_ACCEPT;
				}
			});
			let node = walker.nextNode();
			while (node) {
				polishNode(node);
				node = walker.nextNode();
			}
		} catch {}
		try {
			scope.querySelectorAll('[placeholder], [aria-label], [title], [alt]').forEach((el) => {
				['placeholder', 'aria-label', 'title', 'alt'].forEach((attr) => {
					const original = el.getAttribute(attr);
					if (!original || !/[—–]|\s-\s|[A-Za-zÆØÅæøåÀ-ÖØ-öø-ÿ]\-[A-Za-zÆØÅæøåÀ-ÖØ-öø-ÿ]/.test(original)) return;
					const polished = polishVisibleTextValue(original, true);
					if (polished) el.setAttribute(attr, polished);
				});
			});
		} catch {}
	}

	function startVisibleTextPolisher() {
		polishVisibleText(document);
		try {
			const observer = new MutationObserver((mutations) => {
				mutations.forEach((mutation) => {
					mutation.addedNodes.forEach((node) => {
						if (node.nodeType === Node.TEXT_NODE) {
							polishVisibleText(node.parentElement || document);
						} else if (node.nodeType === Node.ELEMENT_NODE) {
							polishVisibleText(node);
						}
					});
					if (mutation.type === 'characterData') polishVisibleText(mutation.target.parentElement || document);
				});
			});
			observer.observe(document.documentElement, { childList: true, subtree: true, characterData: true });
		} catch {}
	}

